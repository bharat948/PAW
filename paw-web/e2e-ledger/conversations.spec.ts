import { expect, test } from '@playwright/test'

test('durable conversations, checkpoints, fork, forget, rename and deletion', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('paw.token', 'browser-test-token-002b-not-a-secret'))
  await page.goto('/#/agent')
  const input = page.getByLabel('Message Admin Hermès', { exact: true })
  await input.fill('Remember teal')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('article', { name: 'assistant message', exact: true })).toContainText('Acknowledged.')
  await expect(page.getByText('Task checkpoint · completed (agent reported)')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('article', { name: 'user message', exact: true })).toContainText('Remember teal')
  await page.getByRole('button', { name: 'Rename conversation', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Conversation title').fill('Durable investigation')
  await dialog.getByRole('button', { name: 'Save title' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Conversations' })).toContainText('Durable investigation')
  await input.fill('Second question')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('article', { name: 'assistant message', exact: true })).toHaveCount(2)
  const second = page.getByRole('article', { name: 'user message', exact: true }).filter({ hasText: 'Second question' })
  await second.getByRole('button', { name: 'Edit in a new branch' }).click()
  await dialog.getByLabel('Replacement message').fill('Replacement question')
  await dialog.getByRole('button', { name: 'Create branch and send' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('article', { name: 'user message', exact: true }).filter({ hasText: 'Replacement question' })).toBeVisible()
  await expect(page.getByRole('article', { name: 'assistant message', exact: true })).toHaveCount(2)
  await expect(page.getByRole('article', { name: 'user message', exact: true }).filter({ hasText: 'Second question' })).toHaveCount(0)
  const first = page.getByRole('article', { name: 'user message', exact: true }).filter({ hasText: 'Remember teal' })
  await first.getByRole('button', { name: 'Forget this message' }).click()
  await expect(dialog).toContainText('inherited branches and summaries')
  await dialog.getByRole('button', { name: 'Forget message', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByText('Message forgotten', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'All activity', exact: true }).click()
  await expect(page.getByRole('region', { name: 'All activity' })).not.toContainText('Remember teal')
  await page.getByRole('button', { name: 'Back to conversation' }).click()
  await page.getByRole('button', { name: 'Delete conversation', exact: true }).click()
  await expect(dialog).toContainText('Existing forks keep their history')
  await expect(dialog.getByLabel('Also delete delegated conversations')).not.toBeChecked()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Delete conversation', exact: true }).click()
  await dialog.getByRole('button', { name: 'Delete conversation', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Conversations' })).not.toContainText('(fork)')
  expect(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)).toBe(false)
})


test('reload reconnects to an active stream without duplicating the answer', async ({ page, request }) => {
  await page.addInitScript(() => sessionStorage.setItem('paw.token', 'browser-test-token-002b-not-a-secret'))
  await page.goto('/#/agent')
  await page.getByLabel('Message Admin Hermès', { exact: true }).fill('Reconnect this answer')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByText('Acknowledged', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Reconnect this answer', { exact: true })).toBeVisible()
  await expect(page.getByText('Acknowledged', { exact: true })).toBeVisible()
  const response = await request.post('http://127.0.0.1:18002/test/release-runtime')
  expect(response.ok()).toBe(true)
  await expect(page.getByRole('article', { name: 'assistant message', exact: true })).toHaveCount(1)
  await expect(page.getByRole('article', { name: 'assistant message', exact: true })).toContainText('Acknowledged.')
  await expect(page.getByRole('article', { name: 'user message', exact: true })).toHaveCount(1)
})
